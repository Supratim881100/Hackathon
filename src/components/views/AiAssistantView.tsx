import React, { useState, useRef, useEffect } from 'react';
import {
  Bot,
  Trash2,
  AlertTriangle,
  Send,
  Loader2,
  Sparkles,
  User as UserIcon
} from 'lucide-react';
import { api } from '../../services/api.ts';

export const AiAssistantView: React.FC = () => {
  const [messages, setMessages] = useState<Array<{ sender: 'bot' | 'user'; text: string }>>([
    {
      sender: 'bot',
      text: 'Hi! Pick a suggestion or type a question. I can help you find services. I cannot diagnose.'
    }
  ]);
  const [input, setInput] = useState('');
  const [isLoading, setIsLoading] = useState(false);
  const messagesEndRef = useRef<HTMLDivElement>(null);

  const quickPrompts = [
    'How do I book a consultation?',
    'What does hypertension mean in general terms?',
    'How do I find my reports?',
    'How should I prepare for a doctor visit?'
  ];

  const scrollToBottom = () => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  };

  useEffect(() => {
    scrollToBottom();
  }, [messages]);

  const handleSend = async (messageText?: string) => {
    const textToSend = messageText || input;
    if (!textToSend.trim() || isLoading) return;

    const userMessage = { sender: 'user' as const, text: textToSend };
    setMessages((prev) => [...prev, userMessage]);
    setInput('');
    setIsLoading(true);

    try {
      const history = messages.map((m) => ({
        sender: m.sender === 'user' ? 'user' : 'model',
        text: m.text
      }));

      const reply = await api.sendAiChat(textToSend, history);
      setMessages((prev) => [...prev, { sender: 'bot', text: reply }]);
    } catch (err: any) {
      setMessages((prev) => [
        ...prev,
        {
          sender: 'bot',
          text:
            'I am currently operating in navigation mode. You can book an appointment under "Consult a Doctor", view prescriptions in "Health Records", or find pharmacies in "Medicine Locator". For medical emergencies, always call 108 immediately.'
        }
      ]);
    } finally {
      setIsLoading(false);
    }
  };

  const handleClearChat = () => {
    setMessages([
      {
        sender: 'bot',
        text: 'Hi! Pick a suggestion or type a question. I can help you find services. I cannot diagnose.'
      }
    ]);
  };

  return (
    <div className="max-w-4xl mx-auto space-y-6 pb-20">
      {/* Header with Title and Clear Chat */}
      <div className="flex items-center justify-between">
        <div>
          <span className="text-xs font-bold text-[#1b646e] uppercase tracking-wider block">
            BANDAZE
          </span>
          <h1 className="text-2xl sm:text-3xl font-extrabold text-[#0e2c31] tracking-tight mt-0.5">
            AI Health Assistant
          </h1>
        </div>

        <button
          onClick={handleClearChat}
          className="flex items-center gap-1.5 text-xs text-gray-500 hover:text-gray-900 bg-white border border-gray-200 px-3 py-1.5 rounded-xl shadow-2xs transition-colors cursor-pointer"
        >
          <Trash2 className="w-3.5 h-3.5" />
          <span>Clear chat</span>
        </button>
      </div>

      {/* Yellow Disclaimer Banner */}
      <div className="bg-[#fffbeb] border border-[#fef08a] rounded-2xl p-4 flex items-start gap-2.5">
        <AlertTriangle className="w-4 h-4 text-amber-600 flex-shrink-0 mt-0.5" />
        <p className="text-xs text-[#92400e] leading-relaxed">
          Replies are generated by AI (Claude/Gemini) for app navigation and general information only. This is never a diagnosis or prescription. For emergencies call 108.
        </p>
      </div>

      {/* Conversation Container */}
      <div className="bg-white rounded-3xl p-6 border border-gray-150 shadow-2xs min-h-[460px] flex flex-col justify-between space-y-6">
        {/* Messages Scroll Area */}
        <div className="space-y-5 overflow-y-auto max-h-[500px] pr-2 scrollbar-thin">
          {messages.map((m, idx) => (
            <div
              key={idx}
              className={`flex items-start gap-3 ${
                m.sender === 'user' ? 'flex-row-reverse' : ''
              }`}
            >
              {m.sender === 'bot' ? (
                <div className="w-8 h-8 rounded-full bg-[#1e6b75] text-white flex items-center justify-center flex-shrink-0 shadow-xs">
                  <Bot className="w-4.5 h-4.5" />
                </div>
              ) : (
                <div className="w-8 h-8 rounded-full bg-[#10353a] text-white flex items-center justify-center flex-shrink-0 text-xs font-bold">
                  SP
                </div>
              )}

              <div
                className={`text-xs sm:text-sm leading-relaxed ${
                  m.sender === 'user'
                    ? 'bg-[#1e6b75] text-white rounded-2xl rounded-tr-xs px-4 py-3 max-w-md shadow-xs'
                    : 'bg-gray-100/90 text-gray-800 rounded-2xl rounded-tl-xs px-4 py-3.5 max-w-xl whitespace-pre-wrap'
                }`}
              >
                {m.text}
              </div>
            </div>
          ))}

          {isLoading && (
            <div className="flex items-center gap-3">
              <div className="w-8 h-8 rounded-full bg-[#1e6b75] text-white flex items-center justify-center flex-shrink-0">
                <Bot className="w-4.5 h-4.5" />
              </div>
              <div className="bg-gray-100 rounded-2xl rounded-tl-xs px-4 py-3 flex items-center gap-2 text-xs text-gray-500">
                <Loader2 className="w-4 h-4 animate-spin text-teal-700" />
                <span>Thinking...</span>
              </div>
            </div>
          )}

          <div ref={messagesEndRef} />
        </div>

        {/* Bottom Prompts & Input Area */}
        <div className="space-y-3 pt-3 border-t border-gray-100">
          {/* Quick Prompt Pills */}
          <div className="flex flex-wrap items-center gap-2">
            {quickPrompts.map((prompt, i) => (
              <button
                key={i}
                type="button"
                onClick={() => handleSend(prompt)}
                disabled={isLoading}
                className="px-3 py-1.5 rounded-full text-xs bg-white border border-gray-200 text-gray-700 hover:border-teal-500 hover:text-teal-900 transition-colors cursor-pointer text-left shadow-2xs disabled:opacity-50"
              >
                {prompt}
              </button>
            ))}
          </div>

          {/* Input Box */}
          <form
            onSubmit={(e) => {
              e.preventDefault();
              handleSend();
            }}
            className="relative"
          >
            <input
              type="text"
              value={input}
              onChange={(e) => setInput(e.target.value)}
              placeholder="Ask about services, terms, or visit prep..."
              className="w-full pl-4 pr-12 py-3 bg-gray-50/70 border border-gray-200 rounded-2xl text-xs sm:text-sm text-gray-800 placeholder-gray-400 focus:outline-none focus:border-teal-600 focus:bg-white transition-all shadow-2xs"
            />
            <button
              type="submit"
              disabled={isLoading || !input.trim()}
              className="absolute right-2 top-1/2 -translate-y-1/2 w-8 h-8 rounded-xl bg-[#1e6b75] hover:bg-[#165860] text-white flex items-center justify-center transition-colors cursor-pointer disabled:opacity-40"
            >
              <Send className="w-4 h-4" />
            </button>
          </form>
        </div>
      </div>
    </div>
  );
};
